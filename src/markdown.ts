import { diff, exposedPorts, findings } from "./analyze";
import { bytes, date, duration, pct } from "./fmt";
import type { Config, HostState } from "./types";

const cell = (v: unknown) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = (head: string[], rows: unknown[][]) =>
  rows.length ? [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n") + "\n" : "_none_\n";

export function toMarkdown(cfg: Config, state: Record<string, HostState>, notes: Record<string, string>) {
  const out: string[] = [`# Infrastructure Inventory`, ``, `_Generated by Infra Tracker on ${new Date().toLocaleString()}_`, ``];

  out.push(`## Summary`, ``);
  out.push(table(["Host", "Role", "OS", "Uptime", "CPU", "RAM", "Root disk", "Scanned"], cfg.hosts.map((h) => {
    const s = state[h.id]?.latest;
    const root = s?.disks?.find((d) => d.mount === "/");
    return [h.parent ? `↳ ${h.name}` : h.name, h.role, s?.os ?? "–", duration(s?.uptime), s ? `${s.cpu.count}c` : "–",
      s ? bytes(s.memory.total) : "–", root ? `${bytes(root.used)}/${bytes(root.size)} (${pct(root.used, root.size)}%)` : "–",
      s ? date(s.collected_at) : "never"];
  })));

  out.push(`## Exposed services`, ``);
  const svc: unknown[][] = [];
  for (const h of cfg.hosts) {
    const s = state[h.id]?.latest;
    if (!s) continue;
    for (const t of s.tailscale?.serve ?? []) svc.push([h.name, t.url, t.target, "tailnet (serve)"]);
    for (const l of exposedPorts(s)) svc.push([h.name, `${l.proto}/${l.port}`, l.process, "all interfaces"]);
  }
  out.push(table(["Host", "Endpoint", "Backend", "Exposure"], svc));

  out.push(`## Findings`, ``);
  for (const h of cfg.hosts) {
    const st = state[h.id];
    const f = findings(st?.latest ?? null, st?.error ?? null, true);
    if (f.length) out.push(`**${h.name}**`, ``, ...f.map((x) => `- [${x.severity}] ${x.text}`), ``);
  }

  for (const h of cfg.hosts) {
    const st = state[h.id];
    const s = st?.latest;
    out.push(`## ${h.name}`, ``, `- SSH: \`${h.ssh}\``);
    if (h.role) out.push(`- Role: ${h.role}`);
    if (!s) { out.push(`- Not scanned`, ``); continue; }
    out.push(
      `- OS: ${s.os} (kernel ${s.kernel})`,
      `- CPU: ${s.cpu.count}× ${s.cpu.model}`,
      `- RAM: ${bytes(s.memory.total)} (${bytes(s.memory.available)} available)`,
      `- Addresses: ${(s.addresses ?? []).map((a) => `${a.iface} ${a.addrs.join(", ")}`).filter((x) => x.includes(".")).join("; ")}`,
    );
    if (s.tailscale?.ip) out.push(`- Tailscale: ${s.tailscale.ip} (${s.tailscale.dns})${s.tailscale.routes?.length ? `, routes ${s.tailscale.routes.join(", ")}` : ""}`);
    if (s.updates) out.push(`- Updates: ${s.updates.pending ?? "?"} pending${s.updates.reboot_required ? ", **reboot required**" : ""}`);
    out.push(``);

    if (s.proxmox) {
      out.push(`### Guests (Proxmox ${s.proxmox.version})`, ``);
      out.push(table(["ID", "Name", "Type", "Status", "Cores", "RAM", "Disk", "IP"],
        s.proxmox.guests.map((g) => [g.vmid, g.name, g.type, g.status, g.cores, bytes(g.memory), bytes(g.disk), g.ip])));
      out.push(`### Storage`, ``);
      out.push(table(["Name", "Type", "Used", "Total", "Content"],
        s.proxmox.storage.map((x) => [x.name, x.type, bytes(x.used), bytes(x.total), x.content])));
    }
    if (s.docker?.containers.length) {
      out.push(`### Containers`, ``);
      out.push(table(["Name", "Image", "Status", "Compose"], s.docker.containers.map((c) => [c.name, c.image, c.status, c.project])));
      for (const p of s.docker.compose) out.push(`- compose \`${p.name}\`: ${p.config}`);
      out.push(``);
    }
    const us = Object.entries(s.user_services ?? {});
    if (us.length) out.push(`### User services`, ``, ...us.map(([u, l]) => `- ${u}: ${l.join(", ")}`), ``);

    const changes = diff(st.previous, s);
    if (changes.length) out.push(`### Changes since previous scan`, ``, ...changes.map((c) => `- ${c.kind} ${c.area}: ${c.text}`), ``);
    if (notes[h.id]?.trim()) out.push(`### Notes`, ``, notes[h.id].trim(), ``);
  }
  return out.join("\n");
}
